const buf = read('models/人物_puppet.mdl');
const dv2 = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
const mdla = 79842;

// 结构假设: @62 起每 68B 一个骨骼条目
// 条目 = [68 长度 u32][64B 内容]
// 64B 内容可能是 4x4 矩阵 (16 float) 或 [平移3 + 旋转4 + 缩放3 + 更多]
console.log('绑定矩阵条目（@62 起, 68B 步长, 前 12 骨骼）:');
for (let m = 0; m < 12; m++) {
  const o = mdla + 62 + m * 68;
  const len = dv2.getUint32(o, true);
  const vals = [];
  for (let i = 1; i < 16; i++) vals.push(dv2.getFloat32(o + i * 4, true));
  console.log('  B' + String(m).padStart(2) + ' len=' + len + ': [' + vals.map(f => f.toFixed(1)).join(', ') + ']');
}
